export const getAdminDict = (l: Locale) => (l === "ar" ? ar : en);
/** Map a server-action error code to a localized message. */
export const errorText = (l: Locale, code?: string) => {
  const e = getAdminDict(l).errors;
  return (code && e[code]) || e.ERROR;
};
export type { AdminDict };
/** Inline bilingual helper for page-specific admin strings. */
export const tx = (l: Locale) => (enText: string, arText: string) => (l === "ar" ? arText : enText);
